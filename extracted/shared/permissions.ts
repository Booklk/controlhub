/**
 * Check if user can access a specific path
 * التحقق من إمكانية وصول المستخدم لمسار معين
 */
export function canAccessPath(role: string, portal: string, path: string): boolean {
  const navPermissions = PORTAL_NAV_PERMISSIONS[portal];
  if (!navPermissions) return false;
  
  const navPermission = navPermissions.find(p => path.startsWith(p.path));
  if (!navPermission) return false;
  
  return hasPermission(role, navPermission.resource, navPermission.minAction);
}

/**
 * Get allowed navigation items for a user
 * الحصول على عناصر التنقل المسموحة للمستخدم
 */
export function getAllowedNavItems(role: string, portal: string): string[] {
  const navPermissions = PORTAL_NAV_PERMISSIONS[portal];
  if (!navPermissions) return [];
  
  return navPermissions
    .filter(p => hasPermission(role, p.resource, p.minAction))
    .map(p => p.path);
}
