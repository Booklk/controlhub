// ==================== Helper Functions ====================

/**
 * Check if a role has permission for a specific action on a resource
 * التحقق من صلاحية دور معين لإجراء عملية على مورد
 */
export function hasPermission(role: string, resource: Resource, action: Action): boolean {
  const normalizedRole = role === 'admin' ? USER_ROLES.SYSTEM_ADMIN : role;
  const permissions = ROLE_PERMISSIONS[normalizedRole];
  if (!permissions) return false;
  
  const resourcePermission = permissions.find(p => p.resource === resource);
  if (!resourcePermission) return false;
  
  return resourcePermission.actions.includes(action);
}

/**
 * Get all permissions for a role
 * الحصول على جميع صلاحيات دور معين
 */
export function getRolePermissions(role: string): Permission[] {
  const normalizedRole = role === 'admin' ? USER_ROLES.SYSTEM_ADMIN : role;
  return ROLE_PERMISSIONS[normalizedRole] || [];
}

/**
 * Get all allowed resources for a role
 * الحصول على جميع الموارد المسموحة لدور معين
 */
export function getAllowedResources(role: string): Resource[] {
  const normalizedRole = role === 'admin' ? USER_ROLES.SYSTEM_ADMIN : role;
  const permissions = ROLE_PERMISSIONS[normalizedRole];
  if (!permissions) return [];
  return permissions.map(p => p.resource);
}

/**
 * Get allowed actions for a role on a specific resource
 * الحصول على العمليات المسموحة لدور معين على مورد محدد
 */
export function getAllowedActions(role: string, resource: Resource): Action[] {
  const normalizedRole = role === 'admin' ? USER_ROLES.SYSTEM_ADMIN : role;
  const permissions = ROLE_PERMISSIONS[normalizedRole];
  if (!permissions) return [];
  
  const resourcePermission = permissions.find(p => p.resource === resource);
  if (!resourcePermission) return [];
  
  return resourcePermission.actions;
}

